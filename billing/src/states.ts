export function stateFromGstin(gstin: string): string {
  return GSTIN_STATE[gstin.trim().slice(0, 2).toUpperCase()] ?? "";
}

/** "Maharashtra" → "27", as printed beside the place of supply. */
export function stateCode(state: string): string {
  return Object.entries(GSTIN_STATE).find(([, name]) => name === state)?.[0] ?? "";
}

